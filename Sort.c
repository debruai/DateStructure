    CopyList(&L, &original);
    RadixSort(&L, 10, 2);  // 十进制，最大97有2位
    PrintList(&L, "排序结果");
    printf("   是否有序: %s\n", IsSorted(&L) ? "是 ✅" : "否 ❌");

    // 稳定性总结
    printf("\n========== 稳定性总结 ==========\n");
    printf("   稳定：直接插入 / 折半插入 / 冒泡 / 归并 / 基数\n");
